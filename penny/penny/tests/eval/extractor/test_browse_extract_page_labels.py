# ── The claims ───────────────────────────────────────────────────────────────


def _answered(sample: SampleObservation, _world: World) -> Answer:
    """The one closed field left (#2615): did a usable draw come back, rather than the
    extractor exhausting its reroll budget.  Same reading as the sibling case file."""
    drawn = sample.field(EXTRACT_OUTCOME)
    return drawn == MicroExtractOutcome.EXTRACTED.value, f"came back {drawn}"


def _carries(anchor: str) -> WorldClaim:
    """The *nothing omitted* direction: the answer carries one thing the PAGE supplies,
    compared through the shipped ``spoken_form``.  Same reading as the sibling case
    file."""

    def answer(sample: SampleObservation, _world: World) -> Answer:
        value = sample.field(EXTRACT_VALUE)
        carried = spoken_form(anchor) in spoken_form(value)
        return carried, f"not in the extracted value: {value!r}"

    return answer


def _carries_any(*anchors: str) -> WorldClaim:
    """A DISJUNCTIVE ``_carries``: the answer carries at least ONE of the things the page
    supplies.  Used where the fact the issue states is "at least one" — the guard cases
    ask whether the page's substance reached the answer at all, not which of several
    equivalent items the draw picked — and compared word-boundary so a short anchor
    cannot pass by standing inside a longer word."""

    def answer(sample: SampleObservation, _world: World) -> Answer:
        value = spoken_form(sample.field(EXTRACT_VALUE))
        carried = [
            anchor
            for anchor in anchors
            if re.search(rf"\b{re.escape(spoken_form(anchor))}\b", value)
        ]
        return bool(carried), (
            f"none of {anchors!r} in the extracted value: {sample.field(EXTRACT_VALUE)!r}"
        )

    return answer


def _nothing_invented(sample: SampleObservation, _world: World) -> Answer:
    """The *nothing invented* direction: every specific value in the answer traces to
    what the draw was GIVEN.  The claim that holds the #2998 fix's other half — the
    baseline's invented "Senate: 100" totals fail exactly here.  Same reading as the
    sibling case file."""
    invented = unsourced_specifics(sample.output_text, sample.given)
    return not invented, f"not on the page: {invented}"


def _label_carried(name: str, says: str, words: tuple[str, ...]) -> Share:
    """A MEASURED share, never a claim: whether the answer carries the page's own labels
    for its figures, in any of the forms the page writes them.

    Which of a page's several labels a draw picks up — the freshness stamp or the
    for-control figure, "leading" or "to win" — is its own free choice, and the issue's
    ruling for such wording is variance: asserted nowhere, measured here.  Read off the
    extracted value through ``spoken_form``; a sample with no value to read contributes
    nothing (the answered claim above is what judges that)."""

    def reading(sample: SampleObservation) -> ShareReading | None:
        value = sample.field(EXTRACT_VALUE)
        if not value:
            return None
        folded = spoken_form(value)
        hit = [word for word in words if spoken_form(word) in folded]
        return ShareReading(value=1.0 if hit else 0.0, evidence=[value] if hit else [])

    return Share(
        name,
        reading,
        open_above=0.0,
        says=says,
    )


