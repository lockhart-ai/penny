"""The chat history's tool-call line read as part of how her replies look (#2646).

The contract is `docs/eval-case-design.md`.

**Seen (real use, gemma, genericised).**  The user asked "what rule did you not follow
there?" right after a reply that had named shops with no source URL.  Penny named the
rules she had broken, said she would search now, wrote `*Searching for …*` — and then
the plain text `[Tool calls: browse]`, and stopped: `finish_reason: stop`, no tool call
made.  The history she was shown carried the framework's `[Tool calls: …]` line on every
past reply (#2630, merged in #2634), and on several of them TWO lines — one the model had
written itself, one the framework appended — so the line read as part of how her own
replies look, and she reproduced it as text instead of calling the tool.  Her thinking
said exactly that: *the tool call blocks are provided by the system or generated by me?
… It's not a real tool call trigger if it's just text in the response.*

**The case.**  One chat turn over a conversation of the real turn's shape: a running
news job, the two standing rules the user gave, and a nine-exchange history (a rule
stored, a photo of a propagation shelf, plant chatter, a browse-backed factual answer, a
shops errand) whose past replies carry NO tool-call line in their stored text — the real
replies' copied lines are what migration 0121 strips, prod's steady state since it ran —
so the only tool-call line the history shows is the framework's, appended at render off
the seeded runs' own prompt-log records (#2630).  That line is the copy she was
reproducing.  The ask asks which rule the last reply broke.

**The decided fix (code owner) and what the case measures.**  #2646 reverts the
annotation: `_build_conversation` stops appending the line, and the traces behind it go
with it.  This case is its acceptance test: the run before the fix should show the copy
(the reply ends in the line instead of a real call, so no sourced URL reaches the user);
the run after should show the correction — the reply carries a source URL the world
serves.  Whether she browses, and any `[Tool calls` text in the reply, are MEASURED
features, never asserted.

**Claims.**  Facts only.  STORE: what the store held survives — the ask is a question,
and the rules collection is the thing the ask is about.  PROVENANCE: the reply carries a
source URL from a page the world serves (the correction the user asked for), nothing
stored or said is invented.  Whether she names the rule in the store's own words is NOT
claimed: which rule she names is her reading of her own mistake, and a correct answer in
the user's words would fail a key-match claim — it is visible in the reply spread.

**Neighbours.**  `standing-widen-sources` (`test_standing_collection.py`) is re-run
beside this case: the line was added to fix it (#2630), so the case must still hold
after the revert.

REPORT-ONLY (``min_pass_rate=None``): the ceilings these runs propose are the code
owner's to accept once the numbers have been read.  The city, its streets and its
waterfront, the camera model, the user's name and every page host are REAL — hosts are
common-shaped websites (the model never doubts them; the code owner's world rule),
while the page CONTENT is made up — the shop names are plausible for the city; no
name, place or topic from the recorded conversation behind #2646 appears, because the
repo is public.
"""

