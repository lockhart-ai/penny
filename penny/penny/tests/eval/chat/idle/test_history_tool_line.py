@pytest.mark.parametrize("model", EVAL_MODELS)
async def test_asking_which_rule_was_broken_gets_the_sourced_correction(
    chat_eval: ChatEval, model: str
) -> None:
    """A chat turn asked which rule the last reply broke answers with the correction —
    a sourced reply — over a history whose past replies carry the tool-call line.

    The failure this exists to catch is the measured one: the history's own
    ``[Tool calls: …]`` annotation reads as part of how her replies look, so the reply
    reproduces the line as text and stops — no tool call made, no URL for the user."""
    cohort = await chat_eval(
        case_id="history-tool-line-copy",
        behaviour=(
            "In the chat agent, when the user asks which standing rule a recent reply "
            "broke, Penny answers with the correction — a reply that carries a source "
            "URL the world serves — rather than reproducing the history's tool-call "
            "line as text."
        ),
        area=Area.MEMORY,
        model=model,
        seed=_seed_history_tool_line_world,
        prepare=_probe_history_tool_line_world,
        world=_WORLD,
        ask=_ASK,
        also_phrased=_ALSO_PHRASED,
        samples_per_phrasing=3,
        min_pass_rate=None,  # report-only until the numbers are read with the code owner
        family=_FAMILY,
        timeout=240.0,
    )
    # STORE — the ask is a question, so what the store held survives: the two standing
    # rules, the profile, the browse log and the job are what the turn found.
    cohort.assert_what_the_store_held_survives()

    # PROVENANCE — the reply carries the correction the user asked for, and nothing
    # stored or said was invented.  A reply citing an early shop's link from the history
    # is sourced but fails the served-URL claim by name: the correction the rules ask
    # for is a fresh sourced search.
    cohort.claim(
        "reply: it carries a source URL from a page the world serves",
        _the_reply_carries_a_served_url,
        SpecCategory.PROVENANCE,
    )
    cohort.assert_every_value_in_the_store_is_sourced()
    cohort.assert_every_value_in_the_reply_is_sourced()

    cohort.measure(*_MEASURED)
