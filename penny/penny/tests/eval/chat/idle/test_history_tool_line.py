def _log_exchange(db: Database, run_name: str, user_text: str, reply: str, index: int) -> None:
    """One past exchange as the message log holds it: the user's send, then Penny's reply
    stamped with the run id its framework line is read off — the identity pairing the
    conversation builder joins on — and, where the real conversation had one, the
    autonomous announcement after it."""
    run_id = seeded_run_id(run_name)
    ask_id = db.messages.log_message(
        PennyConstants.MessageDirection.INCOMING, TEST_SENDER, user_text
    )
    assert ask_id is not None, f"the seeded ask {user_text!r} failed to log"
    db.messages.log_message(
        PennyConstants.MessageDirection.OUTGOING, "penny", reply, parent_id=ask_id, run_id=run_id
    )
    announcement = _ANNOUNCEMENTS.get(index)
    if announcement:
        db.messages.log_message(
            PennyConstants.MessageDirection.OUTGOING, "penny", announcement, recipient=TEST_SENDER
        )


def _log_run(db: Database, run_name: str, user_text: str) -> None:
    """One seeded run's own prompt-log record: the run id, the conversation as it stood,
    and the response carrying the tool calls the trace reads — one row, since only the
    names across the run's rows reach the history's line."""
    run_id = seeded_run_id(run_name)
    tools = _RUN_TOOLS[run_name]
    if tools:
        response = _seeded_response(
            tool_calls=[
                _wire_tool_call(f"call-seeded-{run_name}-{name}", name, {"reasoning": "seeded"})
                for name in tools
            ]
        )
    else:
        response = _seeded_response()
    conversation = [
        {"role": "user", "content": user_text},
    ]
    _log_chat_step(db, run_id=run_id, messages=conversation, response=response)


def _seed_history_tool_line_world(db: Database) -> None:
    """Lay the case's world down: the user, the profile collection, the browse log, the
    two standing rules and the one running job the conversation left behind, then the
    nine exchanges in her own logs with each run's prompt-log record — every write
    through the store's own chokepoints, so the self-state header renders the seeded
    world the way production rendered it."""
    db.users.save_info(
        sender=TEST_SENDER,
        name=_USER_NAME,
        location=_USER_LOCATION,
        timezone=_USER_TIMEZONE,
        date_of_birth="1990-03-12",
    )
    profile_run = seeded_run_id("history-profile")
    db.memories.create_collection(
        "user_profile", "auto-created to hold 'career'", created_by_run_id=profile_run
    )
    require_memory(db, "user_profile").write(
        [EntryInput(key=key, content=content) for key, content in _PROFILE_ENTRIES],
        author="chat",
        run_id=profile_run,
    )
    require_memory(db, PennyConstants.MEMORY_BROWSE_RESULTS_LOG).append(
        [LogEntryInput(content=content) for content in _BROWSE_ENTRIES], author="chat"
    )
    rules_run = seeded_run_id("history-rules")
    require_memory(db, RULES).write(
        [
            EntryInput(key=_RULE_LINKS_KEY, content=_RULE_LINKS),
            EntryInput(key=_RULE_SEARCH_KEY, content=_RULE_SEARCH),
        ],
        author="chat",
        run_id=rules_run,
    )
    job_run = seeded_run_id(_JOB_CONTAINER)
    db.memories.create_collection(
        _JOB_CONTAINER,
        _JOB_DESCRIPTION,
        extraction_prompt=_JOB_PROGRAM,
        schedule=_JOB_SCHEDULE,
        notify=True,
        created_by_run_id=job_run,
    )
    for index, (user_text, reply, run_name) in enumerate(_EXCHANGES):
        _log_exchange(db, run_name, user_text, reply, index)
        _log_run(db, run_name, user_text)


