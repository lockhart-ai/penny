def _the_reply_carries_a_served_url(sample: SampleObservation, _world: World) -> Answer:
    """The reply carries a source URL from a page the world serves — the correction the
    user asked for (the suggested claim, the code owner rules on it).

    Read through the shared specific-value grammar, so a markdown-wrapped or
    prose-runover address is read as the address it holds.  A URL from an EARLIER turn's
    errand names a host no page serves (the out-of-town shop's own link), so the claim
    fails it by name — the correction the rules ask for is a FRESH sourced search, which
    in this world only a real browse can ground.  A violating sample is nameable: the
    failing turn's shape — the line written instead of the call, the reply ending with
    no URL at all."""
    urls = [value for value in specifics(sample.reply) if value.startswith("http")]
    served = [url for url in urls if any(token_stands_in(host, url) for host in _SHOP_HOSTS)]
    return bool(served), (
        f"the reply states no URL the world serves — it stated {urls or 'no URL at all'}"
    )


# The two readings of ``TOOL_LINE_IN_REPLY``.  Named because a feature's value is a
# diff-join key: one respelling splits its history into two distributions.
_COPIES_THE_LINE = "copies the tool-call line"
_NO_LINE = "no tool-call line"


def _tool_line_reading(sample: SampleObservation) -> str:
    """Whether the reply carries the history's tool-call line as plain text — the
    failure's own signature.

    The line's mark is stable text the framework renders, so a casefold read of the
    reply is the whole reading.  CONSEQUENTIAL: the reply is what the user receives, and
    one carrying the line instead of a call stops mid-turn with nothing done.  It
    declares NO absent reading — a chat sample with no reply is excluded before pooling,
    so no sample this is pooled over read nothing."""
    said = sample.reply.casefold()
    return _COPIES_THE_LINE if "[tool calls" in said else _NO_LINE


TOOL_LINE_IN_REPLY = Feature("tool-call line in the reply", _tool_line_reading)

_MEASURED = (TOOL_SEQUENCE, TOOL_LINE_IN_REPLY, REPLY_SPREAD)


# ── The guards that hold the case to its own facts ────────────────────────────

# No wording may lend the failure's signature or the claims' anchors: no rule key, no
# shop host, no shop name, no tool-call line.
_LEAKS = (*(_RULE_LINKS_KEY, _RULE_SEARCH_KEY), *_SHOP_HOSTS, *_EARLY_SHOP_LINKS, "[tool calls")
for _wording in (_ASK, *_ALSO_PHRASED):
    for _leak in _LEAKS:
        assert _leak not in _wording.casefold(), (
            f"an ask wording must not name {_leak!r}: {_wording!r}"
        )

# The shop hosts must not stand in one another, or a URL naming one could satisfy the
# claim about another.
for _host in _SHOP_HOSTS:
    for _other in _SHOP_HOSTS:
        assert _other is _host or _host not in _other, (
            f"{_host!r} must not be a substring of {_other!r}"
        )

# The shop hosts must reach the turn ONLY through the pages — never through the history,
# where the out-of-town shop is named without a link.  A host the history carried would
# let a copied URL satisfy the claim with no browse at all.
_HISTORY_TEXT = "\n".join(
    f"{user}\n{reply}\n{_ANNOUNCEMENTS.get(index, '')}"
    for index, (user, reply, _run_name) in enumerate(_EXCHANGES)
)
for _host in _SHOP_HOSTS:
    assert _host not in _HISTORY_TEXT.casefold(), (
        f"{_host!r} must come only from a page the world serves, it sits in the history"
    )
# And the out-of-town shop's own link must not stand in a served host — a copied
# earlier-turn link satisfies nothing.
for _early in _EARLY_SHOP_LINKS:
    for _host in _SHOP_HOSTS:
        assert _early not in _host and _host not in _early, (
            f"the early link {_early!r} must not stand in the served host {_host!r}"
        )


